import { describe, expect, it } from 'vitest'
import {
  normalizeMarkdownStrongWhitespace,
  renderMarkdownToSafeHtml,
  sanitizeContentHtml,
  sanitizeInternalContentHtml,
} from './markdown-compatibility'

describe('sanitizeContentHtml', () => {
  it('removes workspace-covering layout declarations while preserving article typography', () => {
    const html = sanitizeContentHtml(`
      <style>.app { display: none }</style>
      <p style="position: fixed; inset: 0; z-index: 2147483647; transform: scale(50); color: #123456; text-align: center; margin: 1em">
        正常正文
      </p>
      <p style="position: sticky; top: 0">置顶正文</p>
    `)
    const document = new DOMParser().parseFromString(html, 'text/html')
    const paragraph = document.querySelector('p')

    expect(document.querySelector('style')).toBeNull()
    expect(paragraph?.style.position).toBe('')
    expect(paragraph?.style.zIndex).toBe('')
    expect(paragraph?.style.inset).toBe('')
    expect(paragraph?.style.transform).toBe('')
    expect(paragraph?.style.color).toBe('rgb(18, 52, 86)')
    expect(paragraph?.style.textAlign).toBe('center')
    expect(paragraph?.style.margin).toBe('1em')
    expect(document.querySelectorAll('p')[1]?.style.position).toBe('')
    expect(document.querySelectorAll('p')[1]?.style.top).toBe('')
  })

  it('removes request-capable CSS values while retaining safe backgrounds', () => {
    const html = sanitizeContentHtml(`
      <p style="background: #f5f7f9">安全背景</p>
      <p style="background-image: url('https://example.test/tracker.png'); list-style: url('https://example.test/marker.png')">危险背景</p>
      <p style="background: u\\72l('https://example.test/escaped.png'); color: #123456">转义网络值</p>
    `)
    const paragraphs = new DOMParser().parseFromString(html, 'text/html').querySelectorAll('p')

    expect(paragraphs[0]?.style.background).toBe('rgb(245, 247, 249)')
    expect(paragraphs[1]?.style.backgroundImage).toBe('')
    expect(paragraphs[1]?.style.listStyle).toBe('')
    expect(paragraphs[2]?.style.background).toBe('')
    expect(paragraphs[2]?.style.color).toBe('rgb(18, 52, 86)')
    expect(html).not.toContain('escaped.png')
  })

  it('removes request-capable image alternatives and untrusted application protocol attributes', () => {
    const html = sanitizeContentHtml(`
      <img
        src="https://example.test/fallback.png"
        srcset="https://example.test/tracker.png 2x"
        data-missing-image-action="replace"
        data-edit-target="title"
        data-untrusted="value"
        alt="正文配图"
      >
    `)
    const image = new DOMParser().parseFromString(html, 'text/html').querySelector('img')

    expect(image?.getAttribute('src')).toBe('https://example.test/fallback.png')
    expect(image?.getAttribute('alt')).toBe('正文配图')
    expect(image?.hasAttribute('srcset')).toBe(false)
    expect(image?.hasAttribute('data-missing-image-action')).toBe(false)
    expect(image?.hasAttribute('data-edit-target')).toBe(false)
    expect(image?.hasAttribute('data-untrusted')).toBe(false)
  })

  it('removes automatic media requests and legacy request-capable attributes', () => {
    const html = sanitizeContentHtml(`
      <table background="https://example.test/tracker.png"><tr><td>正常表格</td></tr></table>
      <video autoplay preload="auto" poster="https://example.test/poster.png" src="https://example.test/video.mp4"><track src="https://example.test/captions.vtt"></video>
      <audio autoplay src="https://example.test/audio.mp3"><source src="https://example.test/audio.ogg"></audio>
      <img src="https://example.test/allowed-image.png" background="https://example.test/legacy.png" alt="正常配图">
      <input type="image" src="https://example.test/input.png">
      <a href="https://example.test/article" ping="https://example.test/ping">正常链接</a>
    `)
    const document = new DOMParser().parseFromString(html, 'text/html')

    expect(document.querySelector('table')?.hasAttribute('background')).toBe(false)
    expect(document.querySelector('video, audio, source, track')).toBeNull()
    expect(document.querySelector('input, button, select, textarea')).toBeNull()
    expect(document.querySelector('img')?.getAttribute('src')).toBe('https://example.test/allowed-image.png')
    expect(document.querySelector('img')?.hasAttribute('background')).toBe(false)
    expect(document.querySelector('a')?.hasAttribute('ping')).toBe(false)
  })

  it('keeps the non-interactive content markers generated by the application', () => {
    const html = sanitizeContentHtml(`
      <aside data-callout="warning" data-callout-title="先备份" data-callout-fold="collapsed">
        <div data-callout-title="">先备份</div>
        <div data-callout-content=""><p>正文</p></div>
      </aside>
      <ul data-type="taskList"><li data-type="taskItem" data-checked="true">完成</li></ul>
      <div data-source-spacer="true" style="height: 1.72em; min-height: 1.72em; display: block"></div>
    `)
    const document = new DOMParser().parseFromString(html, 'text/html')

    expect(document.querySelector('aside')?.dataset).toMatchObject({
      callout: 'warning',
      calloutTitle: '先备份',
      calloutFold: 'collapsed',
    })
    expect(document.querySelector('[data-callout-content]')).not.toBeNull()
    expect(document.querySelector('li')?.dataset).toMatchObject({ type: 'taskItem', checked: 'true' })
    expect(document.querySelector('[data-source-spacer]')?.getAttribute('style')).toContain('height: 1.72em')
  })

  it('only preserves missing-image state through the explicit internal sanitizer', () => {
    const forged = '<img src="https://example.test/image.png" data-missing-id="forged" data-missing-asset="secrets.png">'
    const external = new DOMParser().parseFromString(sanitizeContentHtml(forged), 'text/html').querySelector('img')
    const internal = new DOMParser().parseFromString(sanitizeInternalContentHtml(forged), 'text/html').querySelector('img')

    expect(external?.hasAttribute('data-missing-id')).toBe(false)
    expect(external?.hasAttribute('data-missing-asset')).toBe(false)
    expect(internal?.dataset).toMatchObject({ missingId: 'forged', missingAsset: 'secrets.png' })
  })
})

describe('renderMarkdownToSafeHtml', () => {
  it('renders a single Markdown newline as a visible line break', () => {
    const html = renderMarkdownToSafeHtml('第一行\n第二行')
    const document = new DOMParser().parseFromString(html, 'text/html')

    expect(document.querySelector('p')?.innerHTML).toBe('第一行<br>第二行')
  })

  it('uses an explicit Markdown image title as an optional visible caption', () => {
    const captioned = new DOMParser().parseFromString(
      renderMarkdownToSafeHtml('![流程图](https://example.test/flow.png "图 1：发布流程")'),
      'text/html',
    )
    const plain = new DOMParser().parseFromString(
      renderMarkdownToSafeHtml('![流程图](https://example.test/flow.png)'),
      'text/html',
    )

    expect(captioned.querySelector('figure.article-image-figure > img')?.getAttribute('alt')).toBe('流程图')
    expect(captioned.querySelector('figcaption.article-image-caption')?.textContent).toBe('图 1：发布流程')
    expect(captioned.querySelector('img')?.hasAttribute('title')).toBe(false)
    expect(plain.querySelector('figcaption')).toBeNull()
  })

  it('preserves large embedded image data without leaking internal placeholders', () => {
    const dataUri = `data:image/png;base64,${'QUJD'.repeat(20_000)}`
    const html = renderMarkdownToSafeHtml(`![本地图片](${dataUri})`)

    expect(html).toContain(dataUri)
    expect(html).not.toContain('embedded-image.invalid')
  })

  it('renders an image-rich 4,000-character article without losing embedded images', () => {
    const body = '这是用于验证长文编辑链路的正文。'.repeat(280)
    const images = Array.from({ length: 12 }, (_, index) => (
      `![图片${index + 1}](data:image/png;base64,${'QUJD'.repeat(2_000)})`
    ))
    const html = renderMarkdownToSafeHtml(`${body}\n${images.join('\n')}`)
    const document = new DOMParser().parseFromString(html, 'text/html')

    expect(body.length).toBeGreaterThan(4_000)
    expect(document.querySelectorAll('img')).toHaveLength(12)
    expect(document.body.textContent).toContain(body)
    expect(html).not.toContain('embedded-image.invalid')
  })

  it('repairs whitespace placed after an opening strong marker', () => {
    const markdown = [
      '支持** 100 万 Token 上下文**，也支持正常的 **标准粗体**。',
      '- ** 列表中的粗体**',
      '** 行首粗体**',
    ].join('\n')
    const html = renderMarkdownToSafeHtml(markdown)
    const document = new DOMParser().parseFromString(html, 'text/html')
    const strong = document.querySelectorAll('strong')

    expect(strong).toHaveLength(4)
    expect(strong[0]?.textContent).toBe('100 万 Token 上下文')
    expect(strong[1]?.textContent).toBe('标准粗体')
    expect(strong[2]?.textContent).toBe('列表中的粗体')
    expect(strong[3]?.textContent).toBe('行首粗体')
    expect(document.querySelector('p')?.textContent).toBe('支持 100 万 Token 上下文，也支持正常的 标准粗体。')
  })

  it('repairs whitespace placed before a closing strong marker', () => {
    const markdown = [
      '- **问题选择： **判断哪个问题值得解决；',
      '- **领域理解：  ** 理解行业规则和现场语境；',
    ].join('\n')
    const html = renderMarkdownToSafeHtml(markdown)
    const document = new DOMParser().parseFromString(html, 'text/html')
    const items = document.querySelectorAll('li')

    expect(items[0].innerHTML).toBe('<strong>问题选择：</strong> 判断哪个问题值得解决；')
    expect(items[1].innerHTML).toBe('<strong>领域理解：</strong> 理解行业规则和现场语境；')
  })

  it('does not repair strong-like text inside inline or fenced code', () => {
    const markdown = ['`** 保留空格 **`', '', '```md', '** 保留空格 **', '```'].join('\n')

    expect(normalizeMarkdownStrongWhitespace(markdown)).toBe(markdown)
  })

  it('does not reinterpret escaped strong markers', () => {
    const markdown = String.raw`\** 保留空格 **`

    expect(normalizeMarkdownStrongWhitespace(markdown)).toBe(markdown)
  })

  it('renders the screenshot sentence without exposing strong markers', () => {
    const markdown = '输入费直接翻倍，输出费涨 1.5 倍！请注意，是**整次请求！**都按高价算。'
    const document = new DOMParser().parseFromString(renderMarkdownToSafeHtml(markdown), 'text/html')

    expect(document.querySelector('strong')?.textContent).toBe('整次请求！')
    expect(document.querySelector('p')?.textContent).toBe(markdown.replaceAll('**', ''))
  })

  it.each([
    ['是**“整次请求”**都算', '“整次请求”'],
    ['是**（整次请求）**都算', '（整次请求）'],
    ['是**【整次请求】**都算', '【整次请求】'],
    ['是**！整次请求**都算', '！整次请求'],
    ['是**整次请求：**都算', '整次请求：'],
    ['是**整次请求!**都算', '整次请求!'],
    ['是**"整次请求"**都算', '"整次请求"'],
    ['注意：**整次请求！**都算', '整次请求！'],
    ['请看**“整次请求”**。', '“整次请求”'],
  ])('supports punctuation at strong boundaries: %s', (markdown, expected) => {
    const document = new DOMParser().parseFromString(renderMarkdownToSafeHtml(markdown), 'text/html')

    expect(document.querySelector('strong')?.textContent).toBe(expected)
    expect(document.querySelector('p')?.textContent).toBe(markdown.replaceAll('**', ''))
  })

  it('keeps adjacent strong spans separate when punctuation prevents the first closing marker', () => {
    const markdown = '是**整次请求！**都算，另有**正常加粗**和**“第二处”**要看。'
    const document = new DOMParser().parseFromString(renderMarkdownToSafeHtml(markdown), 'text/html')

    expect(Array.from(document.querySelectorAll('strong'), element => element.textContent))
      .toEqual(['整次请求！', '正常加粗', '“第二处”'])
    expect(document.querySelector('p')?.textContent).toBe(markdown.replaceAll('**', ''))
  })

  it('preserves inline formatting and masks markers inside code, links, and HTML attributes', () => {
    const markdown = '是**“含 *斜体*、`**代码**`、[链接](https://example.test/a**b)和<span title="**属性**">正文</span>！”**都算'
    const document = new DOMParser().parseFromString(renderMarkdownToSafeHtml(markdown), 'text/html')
    const strong = document.querySelector('strong')

    expect(document.querySelectorAll('strong')).toHaveLength(1)
    expect(strong?.querySelector('em')?.textContent).toBe('斜体')
    expect(strong?.querySelector('code')?.textContent).toBe('**代码**')
    expect(strong?.querySelector('a')?.getAttribute('href')).toBe('https://example.test/a**b')
    expect(strong?.querySelector('span')?.getAttribute('title')).toBe('**属性**')
    expect(strong?.textContent).toBe('“含 斜体、**代码**、链接和正文！”')
  })

  it('keeps code examples, escaped delimiters, and incomplete strong markers literal', () => {
    const markdown = [
      '`是**“代码！”**都算`',
      '',
      '```md',
      '是**“围栏！”**都算',
      '```',
      '',
      '    是**“缩进！”**都算',
      '',
      String.raw`是\*\*“转义！”\*\*都算`,
      '',
      String.raw`是**“未闭合！”\*\*都算`,
      '',
      '是**“缺少结尾！',
    ].join('\n')
    const document = new DOMParser().parseFromString(renderMarkdownToSafeHtml(markdown), 'text/html')

    expect(document.querySelector('strong')).toBeNull()
    expect(Array.from(document.querySelectorAll('code'), element => element.textContent?.trim()))
      .toEqual(['是**“代码！”**都算', '是**“围栏！”**都算', '是**“缩进！”**都算'])
    expect(document.body.textContent).toContain('是**“转义！”**都算')
    expect(document.body.textContent).toContain('是**“未闭合！”**都算')
  })

  it('preserves standard nested emphasis and strong punctuation in footnotes', () => {
    const document = new DOMParser().parseFromString(renderMarkdownToSafeHtml([
      '***加粗斜体***，**加粗和 *斜体***，**外层 __内层__ 外层**。正文[^a]',
      '',
      '[^a]: 是**整次请求！**都算',
    ].join('\n')), 'text/html')

    expect(document.querySelector('p em > strong')?.textContent).toBe('加粗斜体')
    expect(document.querySelector('p strong > em')?.textContent).toBe('斜体')
    expect(document.querySelector('p strong > strong')?.textContent).toBe('内层')
    expect(document.querySelector('[data-footnote-content] strong')?.textContent).toBe('整次请求！')
  })

  it('converts Obsidian callouts into semantic editable containers', () => {
    const html = renderMarkdownToSafeHtml([
      '> [!warning] 先备份，再接入同步',
      '> 第一次配置时，先选一台设备作为主设备。',
      '>',
      '> 复制整个 Vault 文件夹作为备份。',
    ].join('\n'))

    const document = new DOMParser().parseFromString(html, 'text/html')
    const callout = document.querySelector('aside[data-callout="warning"]')

    expect(callout?.getAttribute('data-callout-title')).toBe('先备份，再接入同步')
    expect(callout?.querySelector('[data-callout-title]')?.textContent).toBe('先备份，再接入同步')
    expect(callout?.querySelector('[data-callout-content]')?.textContent).toContain('第一次配置时')
    expect(callout?.querySelectorAll('[data-callout-content] p')).toHaveLength(2)
    expect(html).not.toContain('[!warning]')
  })

  it('normalizes callout aliases and preserves fold state', () => {
    const html = renderMarkdownToSafeHtml('> [!abstract]- 本文摘要\n> 摘要正文')
    const document = new DOMParser().parseFromString(html, 'text/html')
    const callout = document.querySelector('aside')

    expect(callout?.dataset.callout).toBe('summary')
    expect(callout?.dataset.calloutFold).toBe('collapsed')
  })

  it('keeps GFM task lists editable instead of flattening their checkboxes', () => {
    const html = renderMarkdownToSafeHtml('- [x] 已完成\n- [ ] 待处理')
    const document = new DOMParser().parseFromString(html, 'text/html')
    const items = document.querySelectorAll('li[data-type="taskItem"]')

    expect(document.querySelector('ul[data-type="taskList"]')).not.toBeNull()
    expect(items).toHaveLength(2)
    expect(items[0].getAttribute('data-checked')).toBe('true')
    expect(items[1].getAttribute('data-checked')).toBe('false')
    expect(document.querySelector('input')).toBeNull()
  })

  it('supports common Obsidian inline syntax without exposing vault-only markup', () => {
    const html = renderMarkdownToSafeHtml('#### 小标题\n\n==重点==、[[说明页|查看说明]]。%%内部备注%%')

    expect(html).toContain('<h4>小标题</h4>')
    expect(html).toContain('<mark>重点</mark>')
    expect(html).toContain('查看说明')
    expect(html).not.toContain('[[')
    expect(html).not.toContain('内部备注')
  })

  it('renders referenced Markdown footnotes with inline formatting and stable numbering', () => {
    const html = renderMarkdownToSafeHtml([
      '正文先引用脚注[^note]，稍后再次引用[^note]，并补充第二条[^2]。',
      '',
      '[^note]: 支持 **加粗** 与 `行内代码`。',
      '[^2]: 第二条说明',
      '    可以跨行书写。',
    ].join('\n'))
    const document = new DOMParser().parseFromString(html, 'text/html')
    const references = document.querySelectorAll('sup[data-footnote-reference]')
    const notes = document.querySelectorAll('[data-footnote-item]')

    expect(references).toHaveLength(3)
    expect(Array.from(references).map(reference => reference.textContent)).toEqual(['1', '1', '2'])
    expect(notes).toHaveLength(2)
    expect(notes[0]?.id).toBe('ez-footnote-1')
    expect(notes[0]?.querySelector('strong')?.textContent).toBe('加粗')
    expect(notes[0]?.querySelector('code')?.textContent).toBe('行内代码')
    expect(notes[1]?.textContent).toContain('第二条说明')
    expect(notes[1]?.textContent).toContain('可以跨行书写')
  })

  it('keeps unknown footnote references literal and sanitizes definition HTML', () => {
    const html = renderMarkdownToSafeHtml([
      '未知引用[^missing]，有效引用[^safe]。',
      '',
      '[^safe]: 安全正文<script>alert(1)</script><img src="x" onerror="alert(2)">',
    ].join('\n'))
    const document = new DOMParser().parseFromString(html, 'text/html')

    expect(document.body.textContent).toContain('[^missing]')
    expect(document.querySelectorAll('[data-footnote-item]')).toHaveLength(1)
    expect(html).not.toContain('<script')
    expect(html).not.toContain('onerror')
  })

  it('does not turn footnote-like text inside code into references', () => {
    const html = renderMarkdownToSafeHtml([
      '有效引用[^note]，代码中保留 `[^note]`。',
      '',
      '```md',
      '[^note]',
      '```',
      '',
      '[^note]: 正常脚注',
    ].join('\n'))
    const document = new DOMParser().parseFromString(html, 'text/html')

    expect(document.querySelectorAll('sup[data-footnote-reference]')).toHaveLength(1)
    expect(document.querySelector('p code')?.textContent).toBe('[^note]')
    expect(document.querySelector('pre')?.textContent).toContain('[^note]')
  })

  it('sanitizes unsafe HTML embedded in Markdown', () => {
    const html = renderMarkdownToSafeHtml('正文<script>alert(1)</script><img src="x" onerror="alert(2)" data-missing-id="forged" data-missing-asset="secrets.png"><video autoplay src="https://example.test/video.mp4"></video>')

    expect(html).not.toContain('<script')
    expect(html).not.toContain('onerror')
    expect(html).not.toContain('data-missing-id')
    expect(html).not.toContain('data-missing-asset')
    expect(html).not.toContain('<video')
  })

  it('preserves extra top-level Markdown blank lines as visible spacers', () => {
    const html = renderMarkdownToSafeHtml('第一段\n\n\n\n第二段')
    const document = new DOMParser().parseFromString(html, 'text/html')

    expect(document.querySelectorAll('[data-source-spacer="true"]')).toHaveLength(2)
    expect(document.querySelector('[data-source-spacer]')?.getAttribute('style')).toContain('height: 1.72em')
    expect(document.body.textContent).toContain('第一段')
    expect(document.body.textContent).toContain('第二段')
  })

  it('keeps one structural blank line invisible and does not alter fenced code spacing', () => {
    const html = renderMarkdownToSafeHtml('第一段\n\n第二段\n\n```text\n第一行\n\n\n第三行\n```')
    const document = new DOMParser().parseFromString(html, 'text/html')

    expect(document.querySelector('[data-source-spacer]')).toBeNull()
    expect(document.querySelector('pre')?.textContent).toContain('第一行\n\n\n第三行')
  })
})
