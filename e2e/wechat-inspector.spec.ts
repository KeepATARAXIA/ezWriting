test('browses image cards, searches original names, and saves or clears recent themes', async ({ page }, info) => {
  await page.addInitScript(() => {
    if (localStorage.getItem('dispatch.wechat-recent-themes.v1') === null) localStorage.setItem('dispatch.wechat-recent-themes.v1', JSON.stringify(['latte', 'morandi-green']))
  })
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.goto('/')
  await page.getByRole('button', { name: '使用公众号长文模板开始' }).click()
  await page.locator('.preview-settings-toggle').click()
  const panel = page.locator('#wechat-theme-panel')
  const recommended = panel.getByRole('region', { name: '推荐模板', exact: true })
  const recent = panel.getByRole('region', { name: '最近使用', exact: true })
  await expect(recommended.locator('footer strong')).toHaveText(['白盒展签', '墨白', '克莱因蓝', '纸上散文'])
  await expect(recent.locator('footer strong')).toHaveText(['咖啡拉花', '莫兰迪绿'])
  const first = (await recommended.locator('.wechat-theme-card').nth(0).boundingBox())!
  const second = (await recommended.locator('.wechat-theme-card').nth(1).boundingBox())!
  expect(Math.abs(first.y - second.y)).toBeLessThan(1)
  expect(second.x).toBeGreaterThan(first.x)
  await panel.locator('img').evaluateAll(elements => Promise.all(elements.map(async element => { element.loading = 'eager'; await element.decode() })))
  await panel.screenshot({ path: info.outputPath('theme-gallery-desktop.png') })
  const search = panel.getByRole('searchbox', { name: '搜索公众号主题' })
  await search.fill('克莱因')
  await expect(panel.locator('.wechat-theme-card footer strong')).toHaveText(['克莱因蓝'])
  await panel.getByRole('button', { name: /^应用克莱因蓝主题/ }).click()
  await expect(page.locator('.wechat-content > [data-wechat-theme]')).toHaveAttribute('data-wechat-theme', 'klein')
  await search.fill('不存在的主题')
  await expect(panel.getByRole('status')).toContainText('没有找到')
  await search.fill('')
  await expect(recent.locator('footer strong').first()).toHaveText('克莱因蓝')
  await panel.getByLabel('自定义主题强调色').evaluate(input => {
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(input, '#335577')
    input.dispatchEvent(new Event('input', { bubbles: true }))
    input.dispatchEvent(new Event('change', { bubbles: true }))
  })
  await expect(page.locator('.wechat-content h2').first()).toHaveCSS('background-color', 'rgb(51, 85, 119)')
  await expect(page.getByLabel('本地保存状态')).toHaveText('已保存')
  await page.reload()
  await page.locator('.preview-settings-toggle').click()
  await expect(recent.locator('footer strong').first()).toHaveText('克莱因蓝')
  await expect(panel.getByLabel('自定义主题强调色')).toHaveValue('#335577')
  await recent.getByRole('button', { name: '清空记录' }).click()
  await expect(recent.locator('.wechat-theme-card')).toHaveCount(0)
  await expect(page.locator('.wechat-content > [data-wechat-theme]')).toHaveAttribute('data-wechat-theme', 'klein')
  await page.reload()
  await page.locator('.preview-settings-toggle').click()
  await expect(recent.locator('.wechat-theme-card')).toHaveCount(0)
  await panel.getByRole('button', { name: '查看全部', exact: true }).click()
  await expect(panel.locator('.wechat-theme-card')).toHaveCount(26)
  await panel.getByRole('button', { name: '返回推荐', exact: true }).click()
  await expect(recommended.locator('.wechat-theme-card')).toHaveCount(4)
  await panel.getByRole('tab', { name: '科技', exact: true }).click()
  await expect(panel.locator('.wechat-theme-card')).not.toHaveCount(0)
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    await page.getByRole('navigation', { name: '手机工作区' }).getByRole('button', { name: '预览', exact: true }).click()
    expect(await panel.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await expect(panel.getByLabel('自定义主题强调色')).toBeInViewport()
    await panel.screenshot({ path: info.outputPath(`theme-gallery-${width}.png`) })
  }
})

test('renders all 26 theme specimens completely and applies each theme on selection', async ({ page }, info) => {
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.goto('/')
  await page.getByRole('button', { name: '使用公众号长文模板开始' }).click()
  await page.locator('.preview-settings-toggle').click()
  const panel = page.locator('#wechat-theme-panel')
  await panel.getByRole('tab', { name: '全部', exact: true }).click()
  const cards = panel.locator('.wechat-theme-card')
  await expect(cards).toHaveCount(26)
  await expect(panel).toHaveCSS('width', '480px')
  const list = panel.locator('.wechat-theme-results')
  const palette = panel.locator('.wechat-palette-dock')
  const categoryTop = (await panel.locator('.wechat-theme-categories').boundingBox())!.y
  const paletteTop = (await palette.boundingBox())!.y
  const firstCard = (await cards.first().boundingBox())!
  expect((await list.boundingBox())!.height / (firstCard.height + 10)).toBeGreaterThanOrEqual(2.5)
  await list.evaluate(element => { element.scrollTop = element.scrollHeight })
  expect((await panel.locator('.wechat-theme-categories').boundingBox())!.y).toBe(categoryTop)
  expect((await palette.boundingBox())!.y).toBe(paletteTop)
  await list.evaluate(element => { element.scrollTop = 0 })
  await page.evaluate(() => document.fonts.ready)
  const pictures = cards.locator('[data-preview-part="image"]')
  const sources = await pictures.evaluateAll(elements => elements.map(element => (element as HTMLImageElement).src))
  expect(new Set(sources).size).toBe(26)
  expect(sources.every(source => source.endsWith('.jpg'))).toBe(true)
  await pictures.evaluateAll(elements => Promise.all(elements.map(async element => {
    const image = element as HTMLImageElement
    image.loading = 'eager'
    await image.decode()
  })))
  const clipped = await cards.evaluateAll(elements => elements.flatMap(card => {
    const viewport = card.querySelector('.wechat-theme-specimen')!.getBoundingClientRect()
    const footer = card.querySelector('footer')!.getBoundingClientRect()
    if (footer.bottom > card.getBoundingClientRect().bottom + 1) return ['clipped card footer']
    const parts = [...card.querySelectorAll('[data-preview-part]:not([data-preview-part="composition"])')]
    return parts.filter(part => {
      const bounds = part.getBoundingClientRect()
      return bounds.bottom > viewport.bottom + 1 || bounds.right > viewport.right + 1 || bounds.left < viewport.left - 1
    }).map(part => `${card.querySelector('footer strong')!.textContent}: ${part.getAttribute('data-preview-part')}`)
  }))
  expect(clipped).toEqual([])
  // Make a review contact sheet from the actual rendered cards, without controls.
  await cards.evaluateAll(elements => {
    const width = elements[0].getBoundingClientRect().width
    const gallery = document.createElement('div')
    gallery.id = 'theme-specimen-contact-sheet'
    gallery.className = 'wechat-theme-rail'
    Object.assign(gallery.style, { position: 'absolute', top: '0', left: '0', zIndex: '9999', width: `${width * 4 + 80}px`, display: 'grid', gridTemplateColumns: `repeat(4, ${width}px)`, gap: '12px', padding: '20px', background: '#f4f6fa', overflow: 'visible' })
    elements.forEach(element => {
      const clone = element.cloneNode(true) as HTMLElement
      clone.classList.remove('selected')
      clone.querySelector('.wechat-theme-check')?.remove()
      clone.querySelector('button')?.remove()
      gallery.append(clone)
    })
    document.body.append(gallery)
  })
  await page.locator('#theme-specimen-contact-sheet img').evaluateAll(elements => Promise.all(elements.map(element => (element as HTMLImageElement).decode())))
  await page.locator('#theme-specimen-contact-sheet').screenshot({ path: info.outputPath('all-26-themes.png') })
  await page.locator('#theme-specimen-contact-sheet').evaluate(element => element.remove())
  for (const card of await cards.all()) {
    const id = await card.locator('[data-preview-theme]').getAttribute('data-preview-theme')
    await card.locator('.wechat-theme-select-target').click()
    await expect(page.locator('.wechat-content > [data-wechat-theme]')).toHaveAttribute('data-wechat-theme', id!)
    await expect(panel.locator('.wechat-palette-dock').getByRole('button', { name: '重置配色' })).toBeVisible()
  }
  await page.setViewportSize({ width: 320, height: 844 })
  await page.getByRole('navigation', { name: '手机工作区' }).getByRole('button', { name: '预览', exact: true }).click()
  const mobileClipped = await cards.evaluateAll(elements => elements.flatMap(card => {
    const viewport = card.querySelector('.wechat-theme-specimen')!.getBoundingClientRect()
    return [...card.querySelectorAll('[data-preview-part]:not([data-preview-part="composition"])')].filter(part => {
      const bounds = part.getBoundingClientRect()
      return bounds.bottom > viewport.bottom + 1 || bounds.right > viewport.right + 1 || bounds.left < viewport.left - 1
    }).map(part => `${card.querySelector('footer strong')!.textContent}: ${part.getAttribute('data-preview-part')}`)
  }))
  expect(mobileClipped).toEqual([])
})

test('applies themes immediately, animates settings and persists the selection', async ({ page }, info) => {
  await page.addInitScript(() => {
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { write: async (items: ClipboardItem[]) => {
      Object.assign(window, { __themeCopy: await (await items[0].getType('text/html')).text() })
    } } })
  })
  await page.setViewportSize({ width: 1674, height: 1000 })
  await page.goto('/')
  await page.getByRole('button', { name: '使用公众号长文模板开始' }).click()
  const source = await page.locator('.cm-content').textContent()
  const theme = page.locator('.wechat-content > [data-wechat-theme]')
  await page.locator('.preview-settings-toggle').click()
  const panel = page.locator('#wechat-theme-panel')
  const choose = panel.getByRole('button', { name: /^应用克莱因蓝主题/ }).first()
  await expect(panel.getByRole('button', { name: '立即应用', exact: true })).toHaveCount(0)
  await expect(panel.getByRole('button', { name: '恢复原样', exact: true })).toHaveCount(0)
  await choose.click()
  await expect(theme).toHaveAttribute('data-wechat-theme', 'klein')
  await expect(choose).toHaveAttribute('aria-pressed', 'true')
  const reveal = panel.locator('.wechat-palette-dock')
  await expect(reveal.locator('.wechat-palette-body')).toHaveCSS('animation-duration', '0.18s')
  await expect(reveal).toHaveCSS('opacity', '1')
  await expect(reveal.getByRole('radio', { name: 'orange', exact: true })).toBeVisible()
  await reveal.getByRole('radio', { name: 'orange', exact: true }).click()
  await expect(theme.locator('h2').first()).toHaveCSS('background-color', 'rgb(240, 106, 42)')
  await page.getByRole('button', { name: '复制公众号格式', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as unknown as { __themeCopy: string }).__themeCopy)).toContain('data-wechat-theme="klein"')
  await expect(page.getByLabel('本地保存状态')).toHaveText('已保存')
  await page.reload()
  await expect(theme).toHaveAttribute('data-wechat-theme', 'klein')
  await expect(page.locator('.cm-content')).toHaveText(source!)
  await page.locator('.preview-settings-toggle').click()
  await expect(panel.locator('.wechat-palette-dock').getByRole('radio', { name: 'orange', exact: true })).toHaveAttribute('aria-checked', 'true')
  await panel.locator('.wechat-theme-card.selected').first().scrollIntoViewIfNeeded()
  await expect(reveal.locator('.wechat-palette-body')).toHaveCSS('opacity', '1')
  await page.screenshot({ path: info.outputPath('theme-instant-desktop.png') })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  expect(await reveal.locator('.wechat-palette-body').evaluate(element => parseFloat(getComputedStyle(element).animationDuration))).toBeLessThan(0.001)
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    await page.getByRole('navigation', { name: '手机工作区' }).getByRole('button', { name: '预览', exact: true }).click()
    await panel.locator('.wechat-palette-dock').scrollIntoViewIfNeeded()
    await panel.locator('.wechat-theme-card.selected').first().scrollIntoViewIfNeeded()
    await expect(reveal.getByRole('button', { name: '重置配色' })).toBeInViewport()
    expect(await panel.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath('theme-instant-' + width + '.png') })
  }
})

