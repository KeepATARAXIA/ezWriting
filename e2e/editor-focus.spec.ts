test('controls both directions of positioning and remembers the setting', async ({ page }, info) => {
  await importContent(page, '# 长文定位\n\n' + Array.from({ length: 90 }, (_, i) => `第${i + 1}段，这是滚动对照测试。${'长文编辑需要准确定位。'.repeat(4)}`).join('\n\n'))
  const left = page.locator('.cm-scroller')
  const right = page.locator('.platform-preview-viewport')
  await left.hover()
  await page.mouse.wheel(0, 1600)
  await expect.poll(() => right.evaluate(node => node.scrollTop)).toBeGreaterThan(300)
  await page.waitForTimeout(700)
  const leftBeforeScroll = await left.evaluate(node => node.scrollTop)
  const selectionBeforeScroll = await page.evaluate(() => window.getSelection()?.toString())
  await right.hover()
  await page.mouse.wheel(0, 2200)
  await expect.poll(() => left.evaluate(node => node.scrollTop)).toBeGreaterThan(leftBeforeScroll + 300)
  expect(await page.evaluate(() => window.getSelection()?.toString())).toBe(selectionBeforeScroll)
  const settledRight = await right.evaluate(node => node.scrollTop)
  await page.waitForTimeout(800)
  expect(await right.evaluate(node => node.scrollTop)).toBeCloseTo(settledRight, 0)
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('switch', { name: '左右同步定位' }).uncheck()
  await page.keyboard.press('Escape')
  const before = await right.evaluate(node => node.scrollTop)
  await left.hover()
  await page.mouse.wheel(0, 1800)
  await page.waitForTimeout(600)
  expect(await right.evaluate(node => node.scrollTop)).toBeCloseTo(before, 0)
  const leftWhileDisabled = await left.evaluate(node => node.scrollTop)
  await right.hover()
  await page.mouse.wheel(0, 1200)
  await page.waitForTimeout(400)
  expect(await left.evaluate(node => node.scrollTop)).toBeCloseTo(leftWhileDisabled, 0)
  const paragraph = page.locator('.wechat-content [data-source-block="30"]').first()
  await paragraph.scrollIntoViewIfNeeded()
  const leftBeforeClick = await left.evaluate(node => node.scrollTop)
  await paragraph.click()
  await page.waitForTimeout(300)
  expect(await left.evaluate(node => node.scrollTop)).toBeCloseTo(leftBeforeClick, 0)
  await page.reload()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await expect(page.getByRole('switch', { name: '左右同步定位' })).not.toBeChecked()
  await page.screenshot({ path: info.outputPath('sync-location-settings.png') })
  await page.getByRole('switch', { name: '左右同步定位' }).check()
  await page.keyboard.press('Escape')
  await paragraph.scrollIntoViewIfNeeded()
  await paragraph.click()
  await expect(page.locator('.source-editor .cm-content')).toBeFocused()
  await expect(page.locator('.source-focus-line')).toBeVisible()
  await expect(page.locator('.source-focus-line')).toContainText('第31段')
})

test('jumps to both editor edges without moving the caret and respects scroll syncing', async ({ page }) => {
  await importContent(page, '# 首尾跳转\n\n' + Array.from({ length: 90 }, (_, i) => `第${i + 1}段。${'长文首尾跳转测试。'.repeat(8)}`).join('\n\n'))
  const left = page.locator('.cm-scroller')
  const right = page.locator('.platform-preview-viewport')
  const editor = page.locator('.cm-content')
  await editor.locator('.cm-line').first().click()
  await page.keyboard.press('ArrowRight')
  const caretBefore = await page.evaluate(() => {
    const selection = window.getSelection()!
    return { text: selection.anchorNode?.textContent, offset: selection.anchorOffset }
  })
  await page.getByRole('button', { name: '到底部', exact: true }).click()
  await expect.poll(() => left.evaluate(node => node.scrollHeight - node.clientHeight - node.scrollTop)).toBeLessThan(2)
  await expect.poll(() => right.evaluate(node => node.scrollTop)).toBeGreaterThan(300)
  await expect(editor).toBeFocused()
  await page.getByRole('button', { name: '到顶部', exact: true }).click()
  await expect.poll(() => left.evaluate(node => node.scrollTop)).toBe(0)
  expect(await page.evaluate(() => {
    const selection = window.getSelection()!
    return { text: selection.anchorNode?.textContent, offset: selection.anchorOffset }
  })).toEqual(caretBefore)
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('switch', { name: '左右同步定位' }).uncheck()
  await page.keyboard.press('Escape')
  const rightBefore = await right.evaluate(node => node.scrollTop)
  await page.getByRole('button', { name: '到底部', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect.poll(() => left.evaluate(node => node.scrollHeight - node.clientHeight - node.scrollTop)).toBeLessThan(2)
  await page.waitForTimeout(300)
  expect(await right.evaluate(node => node.scrollTop)).toBeCloseTo(rightBefore, 0)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '到顶部', exact: true }).click()
  await expect.poll(() => left.evaluate(node => node.scrollTop)).toBe(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})

test('matches both directions after hidden media, HTML siblings and multiline list items', async ({ page }) => {
  const before = Array.from({ length: 18 }, (_, i) => `前文第${i + 1}段。`).join('\n\n')
  const after = Array.from({ length: 18 }, (_, i) => `后文第${i + 1}段。`).join('\n\n')
  await importContent(page, `# 精确定位\n\n${before}\n\n<video controls>\n<source src="./demo.mp4">\n视频回退\n</video>\n\n<p>HTML 第一块</p>\n<p>HTML 第二块</p>\n\n- 列表第一项\n  第一项的续行\n- 列表第二项目标\n\n${after}`)
  const right = page.locator('.wechat-content')
  const target = right.locator('li').filter({ hasText: '列表第二项目标' })
  await target.scrollIntoViewIfNeeded()
  await target.click()
  await expect(page.locator('.source-focus-line')).toContainText('列表第二项目标')
  // Clicking a different source line should center and select that exact preview.
  const leftTarget = page.locator('.cm-line').filter({ hasText: '后文第1段。' })
  await leftTarget.click()
  await expect(right.locator('[data-preview-selected="true"]')).toHaveText('后文第1段。')
  // Same-line clicks must work again after moving the other pane manually.
  await page.locator('.platform-preview-viewport').evaluate(node => { node.scrollTop = 0 })
  await leftTarget.click()
  await expect.poll(() => page.locator('.platform-preview-viewport').evaluate(node => node.scrollTop)).toBeGreaterThan(300)
  const htmlTarget = right.locator('[data-source-line]').filter({ hasText: /^HTML 第二块$/ }).last()
  await htmlTarget.scrollIntoViewIfNeeded()
  await htmlTarget.click()
  await expect(page.locator('.source-focus-line')).toContainText('HTML 第二块')
  await page.getByRole('button', { name: '显示 Markdown 语法', exact: true }).click()
  await target.scrollIntoViewIfNeeded()
  await target.click()
  await expect(page.locator('.source-focus-line')).toContainText('- 列表第二项目标')
  await page.locator('.cm-line').filter({ hasText: '后文第1段。' }).click()
  await expect(right.locator('[data-preview-selected="true"]')).toHaveText('后文第1段。')
})

test('retries failed images and replaces them in the original article', async ({ page }) => {
  let ready = false
  await page.route('https://assets.test/image.png', route => ready ? route.fulfill({ contentType: 'image/png', body: png }) : route.abort())
  await importContent(page, '# 素材修复\n\n![外链图](https://assets.test/image.png)')
  await page.getByRole('button', { name: '文档素材', exact: true }).click()
  const resource = page.locator('.article-resource-card')
  await expect(resource).toContainText('图片加载失败')
  ready = true
  await resource.getByRole('button', { name: '重试', exact: true }).click()
  await expect(resource.locator('img')).toBeVisible()
  await expect.poll(() => resource.locator('img').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBe(1)
  const chooser = page.waitForEvent('filechooser')
  await resource.getByRole('button', { name: '替换', exact: true }).click()
  await (await chooser).setFiles({ name: 'replacement.png', mimeType: 'image/png', buffer: png })
  await expect(resource).toContainText('replacement.png')
  await page.getByRole('button', { name: '正文', exact: true }).click()
  await expect(page.locator('.wechat-content img')).toHaveAttribute('src', /^blob:/)
})

test('applies panel colors directly in preview, copy and restored drafts without changing the source', async ({ page }, testInfo) => {
  await page.addInitScript(() => {
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { write: async (items: ClipboardItem[]) => {
      Object.assign(window, { __focusCopy: await (await items[0].getType('text/html')).text() })
    } } })
  })
  await importContent(page, '<h1>主题覆盖验证</h1><p>普通正文 <strong><span style="color:#00aa55">原文绿色强调</span></strong></p><img src="data:image/png;base64,' + png.toString('base64') + '" style="border:2px solid #00aa55" alt="配图">', true)
  await page.getByRole('button', { name: '显示 Markdown 语法', exact: true }).click()
  const originalSource = await page.locator('.cm-content').textContent()
  await page.locator('.preview-settings-toggle').click()
  await page.getByRole('button', { name: /^预览克莱因蓝主题/ }).click()
  await page.getByRole('button', { name: '立即应用', exact: true }).click()
  await page.locator('.theme-card-colors').getByRole('radio', { name: 'orange', exact: true }).click()
  await expect(page.locator('.wechat-content strong')).toHaveCSS('color', 'rgb(240, 106, 42)')
  await expect(page.locator('.wechat-content strong span')).not.toHaveCSS('color', 'rgb(0, 170, 85)')
  await expect(page.locator('.wechat-content img')).not.toHaveCSS('border-top-color', 'rgb(0, 170, 85)')
  await page.getByRole('button', { name: '复制公众号格式', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as unknown as { __focusCopy: string }).__focusCopy)).toContain('data-wechat-theme="klein"')
  const copied = await page.evaluate(() => (window as unknown as { __focusCopy: string }).__focusCopy)
  expect(copied).not.toContain('rgb(0, 170, 85)')
  expect(copied).not.toContain('data-ez-source-decoration')
  await expect(page.getByLabel('本地保存状态')).toHaveText('已保存')
  // Exercise a legacy saved policy: reopening must still honor the visible controls.
  await page.evaluate(() => new Promise<void>((resolve, reject) => {
    const request = indexedDB.open('dispatch-workbench-local')
    request.onerror = () => reject(request.error)
    request.onsuccess = () => {
      const database = request.result
      const transaction = database.transaction('drafts', 'readwrite')
      const store = transaction.objectStore('drafts')
      const drafts = store.getAll()
      drafts.onsuccess = () => {
        for (const draft of drafts.result) store.put({ ...draft, formatting: { ...draft.formatting, sourceStyle: 'preserve' } })
      }
      transaction.oncomplete = () => { database.close(); resolve() }
      transaction.onerror = () => { database.close(); reject(transaction.error) }
    }
  }))
  await page.reload()
  await page.locator('.preview-settings-toggle').click()
  await expect(page.locator('.wechat-content strong')).toHaveCSS('color', 'rgb(240, 106, 42)')
  await expect(page.locator('.cm-content')).toHaveText(originalSource!)
  await page.screenshot({ path: testInfo.outputPath('theme-policy-1440.png') })
})
