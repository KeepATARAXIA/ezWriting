test('moves and resizes polishing, ignores backdrop and Escape, closes only explicitly', async ({ page }) => {
  await setup(page); await selectText(page)
  const dialog = page.getByRole('dialog', { name: 'AI 选段润色' })
  await page.keyboard.press('Escape')
  await page.mouse.click(5, 5)
  await expect(dialog).toBeVisible()
  const before = await dialog.boundingBox()
  const title = await dialog.locator('header h2').boundingBox()
  await page.mouse.move(title!.x + 30, title!.y + 10); await page.mouse.down()
  await page.mouse.move(title!.x + 70, title!.y + 40, { steps: 5 }); await page.mouse.up()
  const moved = await dialog.boundingBox()
  expect(moved!.x).toBeCloseTo(before!.x + 40, 0)
  expect(moved!.y).toBeCloseTo(before!.y + 30, 0)
  const handle = await dialog.locator('.dialog-resize-se').boundingBox()
  await page.mouse.move(handle!.x + 5, handle!.y + 5); await page.mouse.down()
  await page.mouse.move(handle!.x - 85, handle!.y + 65, { steps: 5 }); await page.mouse.up()
  const resized = await dialog.boundingBox()
  expect(resized!.width).toBeCloseTo(moved!.width - 90, 0)
  expect(resized!.height).toBeCloseTo(moved!.height + 60, 0)
  await page.setViewportSize({ width: 800, height: 600 })
  const clamped = await dialog.boundingBox()
  expect(clamped!.x).toBeGreaterThanOrEqual(0)
  expect(clamped!.x + clamped!.width).toBeLessThanOrEqual(800)
  expect(clamped!.y + clamped!.height).toBeLessThanOrEqual(600)
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await selectText(page)
  await page.getByRole('button', { name: '关闭AI 选段润色' }).click()
  await expect(dialog).toHaveCount(0)
})

