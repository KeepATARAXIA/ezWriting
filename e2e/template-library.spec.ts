test('inserts a sanitized HTML template over the selected body text', async ({ page }) => {
  await page.goto('/')
  await page.locator('input[accept*=".md"]').setInputFiles({ name: 'replace.md', mimeType: 'text/markdown', buffer: Buffer.from('# 保留标题\n\n替换这一段\n\n保留下一段') })
  await page.locator('.cm-line').filter({ hasText: '替换这一段' }).click()
  await page.keyboard.press('Home')
  await page.keyboard.press('Shift+End')
  await openLibrary(page)
  await page.locator('.library-create-actions summary').click()
  await page.getByRole('button', { name: '新建文字模板', exact: true }).click()
  await page.getByLabel('素材名称', { exact: true }).fill('HTML 结尾')
  await page.getByRole('combobox', { name: '内容格式' }).selectOption('html')
  await page.getByLabel('模板内容', { exact: true }).fill('<p><strong>新的结尾</strong></p><script>window.libraryInjected = true</script>')
  await page.getByRole('button', { name: '保存到素材库', exact: true }).click()
  await page.getByRole('button', { name: '添加到编辑器：HTML 结尾', exact: true }).click()
  await expect(page.locator('.wechat-content strong')).toHaveText('新的结尾')
  await expect(page.locator('.wechat-content')).not.toContainText('替换这一段')
  await expect(page.locator('.wechat-content')).toContainText('保留下一段')
  await expect(page.locator('.topbar-document-title')).toHaveText('保留标题')
  expect(await page.evaluate(() => 'libraryInjected' in window)).toBe(false)
  await page.locator('.source-toolbar').getByRole('button', { name: '撤销', exact: true }).click()
  await expect(page.locator('.wechat-content')).toContainText('替换这一段')
})

test('keeps the editor usable beside the library, drops at the pointer, and collapses from the rail', async ({ page }, info) => {
  await page.goto('/')
  await page.locator('input[accept*=".md"]').setInputFiles({ name: 'drop.md', mimeType: 'text/markdown', buffer: Buffer.from('# 拖拽测试\n\n第一段保留\n\n目标位置\n\n末段保留') })
  await openLibrary(page)
  await expect(page.getByRole('dialog', { name: '模板素材库' })).toHaveCount(0)
  const sidebar = page.getByRole('complementary', { name: '模板素材库' })
  expect(await page.locator('.workbench-toolbar').evaluate(node => node.getBoundingClientRect().right)).toBeLessThanOrEqual(1440)
  expect(await page.locator('.preview-lane').evaluate(node => node.getBoundingClientRect().right)).toBeLessThanOrEqual(1440)
  const body = page.locator('.cm-line').filter({ hasText: '目标位置' })
  await body.click()
  await page.keyboard.press('End')
  await page.keyboard.insertText('继续编辑')
  await expect(page.locator('.wechat-content')).toContainText('目标位置继续编辑')
  await page.locator('.template-library input[type=file]').setInputFiles({ name: '拖拽图.gif', mimeType: 'image/gif', buffer: Buffer.from(gif, 'base64') })
  await page.getByRole('button', { name: '保存到素材库', exact: true }).click()
  const card = page.locator('.library-card').filter({ hasText: '拖拽图.gif' })
  await expect(card).toBeVisible()
  // Keep the old cursor on the last paragraph; the drop must use the pointer instead.
  await page.locator('.cm-content').press('Control+End')
  await card.locator('.library-card-preview').dragTo(body, { targetPosition: { x: 2, y: 10 } })
  await expect(page.locator('.source-image-widget')).toHaveCount(1)
  await expect(sidebar).toBeVisible()
  await expect(page.locator('.wechat-content img')).toHaveCount(1)
  const blocks = await page.locator('.wechat-content').evaluate(node => Array.from(node.querySelectorAll('p, img')).map(child => child.tagName === 'IMG' ? 'IMAGE' : child.textContent))
  expect(blocks.indexOf('IMAGE')).toBeGreaterThan(blocks.findIndex(text => text?.includes('第一段保留')))
  expect(blocks.indexOf('IMAGE')).toBeLessThan(blocks.findIndex(text => text?.includes('目标位置继续编辑')))
  await page.screenshot({ path: info.outputPath('library-sidebar-desktop.png') })
  await page.locator('.source-toolbar').getByRole('button', { name: '撤销', exact: true }).click()
  await expect(page.locator('.source-image-widget')).toHaveCount(0)
  await expect(page.locator('.wechat-content')).toContainText('目标位置继续编辑')
  await body.click()
  await page.keyboard.press('Home')
  await page.keyboard.press('Shift+End')
  const collect = page.getByRole('button', { name: '收藏到模板库', exact: true })
  await expect(collect).toHaveText('')
  await expect(collect).toHaveAttribute('title', '收藏到模板库')
  await collect.click()
  await expect(page.getByLabel('模板内容', { exact: true })).toHaveValue('目标位置继续编辑')
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: '模板素材库', exact: true }).click()
  await expect(sidebar).toBeVisible()
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: '新建文档', exact: true }).click()
  await expect(page.getByLabel('模板内容', { exact: true })).toHaveValue('目标位置继续编辑')
  await page.getByRole('button', { name: '保存到素材库', exact: true }).click()
  const textCard = page.locator('.library-card.text')
  const lastLine = page.locator('.cm-line').filter({ hasText: '末段保留' })
  await textCard.locator('.library-card-preview').dragTo(lastLine, { targetPosition: { x: 2, y: 10 } })
  await expect(page.locator('.wechat-content')).toContainText('目标位置继续编辑末段保留')
  await expect(sidebar).toBeVisible()
  await page.locator('.source-toolbar').getByRole('button', { name: '撤销', exact: true }).click()
  await expect(page.locator('.wechat-content')).not.toContainText('目标位置继续编辑末段保留')
  await page.setViewportSize({ width: 1000, height: 900 })
  const paper = await page.locator('.paper-panel').boundingBox()
  const library = await sidebar.boundingBox()
  expect(library!.x).toBe(72)
  expect(library!.x + library!.width).toBeLessThanOrEqual(paper!.x)
  expect(paper!.x + paper!.width).toBeLessThanOrEqual(1000)
  await page.setViewportSize({ width: 390, height: 844 })
  const mobilePaper = await page.locator('.paper-panel').boundingBox()
  const mobileLibrary = await sidebar.boundingBox()
  expect(mobilePaper!.y + mobilePaper!.height).toBeLessThanOrEqual(mobileLibrary!.y + 1)
  await page.screenshot({ path: info.outputPath('library-sidebar-mobile.png') })
  await page.getByRole('button', { name: '模板素材库', exact: true }).click()
  await expect(sidebar).toHaveCount(0)
  await expect(page.getByRole('button', { name: '模板素材库', exact: true })).toBeFocused()
  await openLibrary(page)
  await page.keyboard.press('Escape')
  await expect(sidebar).toHaveCount(0)
})
