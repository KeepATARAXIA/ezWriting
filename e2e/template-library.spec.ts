test('collects selected Markdown, inserts it in another draft, and preserves undo and reload', async ({ page }, info) => {
  await page.goto('/')
  const sentence = '**这句话值得反复使用**，保留原有格式。'
  await page.locator('input[accept*=".md"]').setInputFiles({ name: 'collect.md', mimeType: 'text/markdown', buffer: Buffer.from(`# 收藏测试\n\n${sentence}\n\n原文的下一段。`) })
  const line = page.locator('.cm-line').filter({ hasText: '这句话值得反复使用' })
  await line.click()
  await page.keyboard.press('Home')
  await page.keyboard.press('Shift+End')
  await page.getByRole('button', { name: '收藏到模板库', exact: true }).click()
  await expect(page.getByLabel('模板内容', { exact: true })).toHaveValue(sentence)
  await page.getByLabel('素材名称', { exact: true }).fill('常用金句')
  await page.getByLabel('素材分类', { exact: true }).fill('金句')
  await page.getByRole('button', { name: '保存到素材库', exact: true }).click()
  await expect(page.locator('.library-notice')).toContainText('素材已保存')
  await page.screenshot({ path: info.outputPath('collected-text.png') })
  await page.getByRole('button', { name: '关闭模板素材库', exact: true }).click()
  await expect(page.locator('.wechat-content')).toContainText('原文的下一段。')
  await page.getByRole('button', { name: '新建文档', exact: true }).click()
  await page.getByRole('button', { name: '空白文档', exact: true }).click()
  await editTitle(page, '另一篇文章')
  await page.locator('.cm-content').press('Control+End')
  await openLibrary(page)
  await page.getByRole('button', { name: '添加到编辑器：常用金句', exact: true }).click()
  await expect(page.locator('.wechat-content strong')).toContainText('这句话值得反复使用')
  await expect(page.locator('.topbar-document-title')).toHaveText('另一篇文章')
  await page.locator('.source-toolbar').getByRole('button', { name: '撤销', exact: true }).click()
  await expect(page.locator('.wechat-content')).not.toContainText('这句话值得反复使用')
  await expect(page.locator('.topbar-document-title')).toHaveText('另一篇文章')
  await page.locator('.source-toolbar').getByRole('button', { name: '重做', exact: true }).click()
  await expect(page.getByLabel('本地保存状态')).toHaveText('已保存')
  await page.reload()
  await expect(page.locator('.wechat-content strong')).toContainText('这句话值得反复使用')
  await openLibrary(page)
  await expect(page.locator('.library-card')).toHaveCount(1)
})

