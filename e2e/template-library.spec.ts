test('uploads and categorizes images, inserts an independent copy, and retains it after library deletion', async ({ page }, info) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始写稿' }).click()
  await editTitle(page, '图片复用')
  await page.locator('.cm-content').press('Control+Home')
  await openLibrary(page)
  await page.locator('.template-library input[type=file]').setInputFiles([
    { name: '常用表情.gif', mimeType: 'image/gif', buffer: Buffer.from(gif, 'base64') },
    { name: '品牌图.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="120" height="80"><rect width="120" height="80" fill="#1648ff"/></svg>') },
  ])
  await page.getByLabel('素材分类', { exact: true }).fill('日常配图')
  await page.getByRole('button', { name: '保存到素材库', exact: true }).click()
  await expect(page.locator('.library-card')).toHaveCount(2)
  const row = await page.locator('.library-card').first().boundingBox()
  expect(row!.height).toBeGreaterThanOrEqual(70)
  expect(row!.height).toBeLessThanOrEqual(90)
  expect((await page.locator('.template-library-sidebar').boundingBox())!.width).toBe(280)
  await page.screenshot({ path: info.outputPath('library-images.png') })
  await page.getByRole('button', { name: '关闭模板素材库', exact: true }).click()
  await expect(page.getByLabel('本地保存状态')).toHaveText('已保存')
  await page.reload()
  await expect(page.locator('.topbar-document-title')).toHaveText('图片复用')
  await openLibrary(page)
  await expect(page.locator('.library-card img')).toHaveCount(2)
  await page.locator('.library-filter-menu summary').click()
  await page.getByLabel('筛选素材分类').selectOption({ label: '日常配图' })
  await page.locator('.library-filter-menu summary').click()
  await page.getByRole('button', { name: '添加到编辑器：常用表情.gif', exact: true }).click()
  await expect(page.locator('.source-image-widget')).toBeVisible()
  await expect(page.locator('.topbar-document-title')).toHaveText('图片复用')
  await expect(page.locator('.wechat-content img')).toHaveCount(1)
  await expect(page.getByLabel('本地保存状态')).toHaveText('已保存')
  await openLibrary(page)
  await page.locator('.library-card').filter({ hasText: '常用表情.gif' }).hover()
  await page.getByRole('button', { name: '删除素材：常用表情.gif', exact: true }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.locator('.library-card')).toHaveCount(1)
  await page.getByRole('button', { name: '关闭模板素材库', exact: true }).click()
  await page.reload()
  await expect(page.locator('.source-image-widget')).toBeVisible()
  await expect(page.locator('.wechat-content img')).toHaveCount(1)
  expect(await page.locator('.wechat-content img').evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true)
})

