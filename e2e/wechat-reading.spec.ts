import { expect, test } from '@playwright/test'

test('identifies the editable title, fills the footer and matches WeChat reading chrome', async ({ page }, info) => {
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.goto('/')
  await page.locator('input[accept*=".md"]').setInputFiles({ name: 'reading.md', mimeType: 'text/markdown',
    buffer: Buffer.from('# 手机阅读样式\n\n第一段正文。\n\n第二段正文。\n\n' + '向下阅读，底部操作始终可见。\n\n'.repeat(35)) })
  const title = page.locator('.cm-article-title')
  await expect(title).toHaveAttribute('aria-label', '文章标题')
  expect(await title.evaluate(node => getComputedStyle(node, '::before').content)).toContain('文章标题')
  await page.locator('.cm-content').press('Control+Home')
  await page.keyboard.press('End')
  await page.keyboard.insertText(' 新标题')
  await expect(page.locator('.wechat-document > h1')).toHaveText('手机阅读样式 新标题')
  await page.keyboard.press('Control+z')
  await expect(page.locator('.wechat-document > h1')).toHaveText('手机阅读样式')
  await page.keyboard.press('Control+y')
  await expect(page.locator('.wechat-document > h1')).toHaveText('手机阅读样式 新标题')
  await expect(page.getByLabel('本地保存状态')).toHaveText('已保存')
  await page.reload()
  await expect(title).toContainText('新标题')
  expect(await page.locator('.wechat-content').textContent()).not.toContain('手机阅读样式')
  expect(await page.locator('.wechat-document > h1').evaluate(node => getComputedStyle(node).fontFamily)).toContain('Microsoft YaHei')
  await expect.poll(() => page.locator('.source-row-stripe').evaluateAll(nodes => nodes.some(node => {
    const stripe = node.getBoundingClientRect()
    return [...document.querySelectorAll('.cm-line:not(.cm-article-title)')].some(line => {
      const box = line.getBoundingClientRect()
      return Math.abs(box.top - stripe.top) < 1 && Math.abs(box.width + 24 - stripe.width) < 1 && Math.abs(box.left - 12 - stripe.left) < 1
    })
  }))).toBe(true)
  expect(await page.locator('.source-editor-statusbar').evaluate(node => {
    const box = node.getBoundingClientRect()
    const panel = node.closest('.paper-panel')!.getBoundingClientRect()
    return Math.abs(box.left - panel.left) <= 2 && Math.abs(box.right - panel.right) <= 2
  })).toBe(true)
  await page.screenshot({ path: info.outputPath('editor-reading-surfaces.png') })
  await page.getByRole('button', { name: '手机预览', exact: true }).click()
  await expect(page.locator('.wechat-original')).toHaveText('原创')
  await expect(page.getByLabel('发布时间')).toHaveText('待发布')
  await expect(page.locator('.wechat-reading-actions > span')).toHaveCount(4)
  const footer = page.locator('.wechat-reading-footer')
  const footerBefore = await footer.boundingBox()
  await page.locator('.mobile-article-scroll').evaluate(node => { node.scrollTop = node.scrollHeight })
  await expect(footer).toBeVisible()
  expect(await footer.boundingBox()).toEqual(footerBefore)
  await page.locator('.mobile-article-scroll').evaluate(node => { node.scrollTop = 0 })
  await page.screenshot({ path: info.outputPath('wechat-reading-desktop.png') })
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 390, height: 900 })
  await page.getByRole('navigation', { name: '手机工作区' }).getByRole('button', { name: '预览', exact: true }).click()
  await page.getByRole('button', { name: '手机预览', exact: true }).click()
  await expect(footer).toBeVisible()
  expect(await page.locator('.mobile-wechat-content').evaluate(node => (node as HTMLElement).offsetWidth)).toBe(350)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('wechat-reading-mobile.png') })
})
