test('shows actionable failures, keeps partial output, and clears every key', async ({ page }) => {
  let calls = 0
  await page.route('**/api/ai/generate', async route => {
    calls++
    if (calls === 1) await route.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: { code: 'invalid_key' } }) })
    else await route.fulfill({ contentType: 'text/event-stream', body: frame({ type: 'delta', text: '收到一半的文字' }) + frame({ type: 'error', code: 'truncated' }) })
  })
  await page.goto('/')
  await openAi(page)
  await page.getByLabel('API Key', { exact: true }).fill('gemini-test-key')
  await page.getByRole('button', { name: '测试连接', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('API Key 无效或已过期')
  await page.getByRole('button', { name: '生成文字', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('输出达到长度上限')
  await expect(page.getByRole('region', { name: '生成结果', exact: true })).toContainText('未完成')
  await expect(page.getByRole('region', { name: '生成结果', exact: true })).toContainText('收到一半的文字')
  await page.getByLabel('模型', { exact: true }).selectOption('glm')
  await page.getByLabel('API Key', { exact: true }).fill('glm-test-key')
  await page.getByRole('button', { name: '清除所有 Key', exact: true }).click()
  await expect(page.getByLabel('API Key', { exact: true })).toHaveValue('')
  await page.getByLabel('模型', { exact: true }).selectOption('gemini')
  await expect(page.getByLabel('API Key', { exact: true })).toHaveValue('')
  expect(calls).toBe(2)
})

test('renders incremental text, prevents duplicate requests, and cancels on stop and close', async ({ page }) => {
  await page.addInitScript(() => {
    const original = window.fetch
    const state = { calls: 0, aborted: 0 }
    Object.assign(window, { __aiTest: state })
    window.fetch = async (input, init) => {
      if (input !== '/api/ai/generate') return original(input, init)
      state.calls++
      const body = new ReadableStream<Uint8Array>({ start(controller) {
        controller.enqueue(new TextEncoder().encode('data: {"type":"delta","text":"逐步出现的文字"}\n\n'))
        init?.signal?.addEventListener('abort', () => { state.aborted++; controller.error(new DOMException('Aborted', 'AbortError')) })
      } })
      return new Response(body, { headers: { 'Content-Type': 'text/event-stream' } })
    }
  })
  await page.goto('/')
  await openAi(page)
  await page.getByLabel('API Key', { exact: true }).fill('test-key')
  await page.getByRole('button', { name: '生成文字', exact: true }).click()
  await expect(page.getByRole('region', { name: '生成结果', exact: true })).toContainText('逐步出现的文字')
  await expect(page.getByLabel('模型', { exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '测试连接', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '停止', exact: true }).click()
  await expect(page.getByRole('complementary', { name: 'AI 工具', exact: true }).getByRole('status')).toContainText('已停止请求')
  await expect(page.getByRole('region', { name: '生成结果', exact: true })).toContainText('未完成')
  await page.getByRole('button', { name: '生成文字', exact: true }).click()
  await expect(page.getByRole('button', { name: '停止', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  expect(await page.evaluate(() => (window as unknown as { __aiTest: unknown }).__aiTest)).toEqual({ calls: 2, aborted: 2 })
  await openAi(page)
  await expect(page.getByLabel('API Key', { exact: true })).toHaveValue('test-key')
  await expect(page.getByRole('region', { name: '生成结果', exact: true })).toHaveCount(0)
})


test('reports blocked persistence while allowing the current page to use the key', async ({ page }) => {
  await page.addInitScript(() => {
    const original = Storage.prototype.setItem
    Storage.prototype.setItem = function (key, value) {
      if (key === 'dispatch.ai-settings.v1') throw new DOMException('Blocked', 'QuotaExceededError')
      return original.call(this, key, value)
    }
  })
  await page.goto('/')
  await openAi(page)
  await page.getByLabel('API Key', { exact: true }).fill('mock-unsaved-key')
  await expect(page.getByRole('alert')).toContainText('浏览器未能保存本次配置')
  await expect(page.getByRole('button', { name: '测试连接', exact: true })).toBeEnabled()
  await page.reload()
  await openAi(page)
  await expect(page.getByLabel('API Key', { exact: true })).toHaveValue('')
})
